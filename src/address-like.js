// 住所らしさの判定 ---------------------------------------------------------------
// タイムズの住所の読み取り（times.js）と、料金の記録の補記の条件（record-gap.js）で同じものを使う（2026-10-18）。
// 補記の条件が「都道府県市区町村郡の字が1つでもあれば住所」というゆるい判定だったので、タイムズの題名のかっこを
// 住所と取り違えていた「京都市総合教育センター」「さがみ信用金庫緑町支店」「西宮市立北口」なども「もう住所がある」と
// みなされ、正しい住所が読めるようになっても料金の記録に残らなかった（5件）。

const PREFS = "北海道|青森県|岩手県|宮城県|秋田県|山形県|福島県|茨城県|栃木県|群馬県|埼玉県|千葉県|東京都|神奈川県"
  + "|新潟県|富山県|石川県|福井県|山梨県|長野県|岐阜県|静岡県|愛知県|三重県|滋賀県|京都府|大阪府|兵庫県|奈良県"
  + "|和歌山県|鳥取県|島根県|岡山県|広島県|山口県|徳島県|香川県|愛媛県|高知県|福岡県|佐賀県|長崎県|熊本県|大分県"
  + "|宮崎県|鹿児島県|沖縄県";
// 都道府県のすぐ後に市区町村郡が続くもの。「京都府立医大」「東京都庁」のような名前のかっこは住所にしない
const PREF_ADDR = new RegExp(`^(?:${PREFS}).{0,10}?[市区町村郡]`);
// 都道府県が無くても、市区町村郡で始まり番地（数字）・丁目・番地のあるもの（例: 札幌市中央区北3条西2）
const MUNI_ADDR = /^[^\d０-９]{1,10}?[市区町村郡].*(?:[0-9０-９]|丁目|番地)/;
// 市区町村の字を含んでも住所ではない言葉（「京都市総合教育センター」「西宮市立北口」「第2区画」「〜支店」など）
export const NOT_ADDR = /(?:センター|病院|医院|駐車|パーキング|専用|ビル|モール|大学|学校|公園|ホテル|役所|役場|区画|支店|銀行|金庫|店$|[都道府県市区町村]立)/;

/** 都道府県＋市区町村郡で始まるか */
export const isPrefAddress = (s) => PREF_ADDR.test(s);
/** 市区町村郡で始まり、番地・丁目などが続くか（施設名の言葉を含むものは除く） */
export const isMuniAddress = (s) => MUNI_ADDR.test(s) && !NOT_ADDR.test(s);

/** 住所らしいか。都道府県＋市区町村郡で始まる、または市区町村郡で始まって番地・丁目などが続く。
 *  空・物件名・「上層階」「第２」・「京都市総合教育センター」のような施設名は住所とみなさない */
export function isAddressLike(s) {
  if (typeof s !== "string") return false;
  const t = s.trim();
  return !!t && (isPrefAddress(t) || isMuniAddress(t));
}

/** かっこが閉じないまま終わっている（途中で切れた）住所か。
 *  タイムズの題名から読んでいたころ、住所の中のかっこで切れていた（「北海道札幌市白石区本通（北」「…鶴馬（大字」など34件） */
export const isTruncatedAddress = (s) => typeof s === "string" && /[（(][^）)]*$/.test(s.trim());
