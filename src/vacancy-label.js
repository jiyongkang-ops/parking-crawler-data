// 満空の言葉を1か所に持つ。
// 事業者ごとに同じ対応表を書くと、片方だけ言い換えたときに jsonl に2種類の語が混ざり、
// 集計（studio-push の重み付け）が黙って合わなくなる。
// いまのところ NPC・三井のリパークとも 0=空 / 1=混雑 / 2=満車 で同じ並び。
const MAP = { 0: "空", 1: "混雑", 2: "満車" };

/** 事業者のコード → 表示用の言葉。読めなければ null（満空なしとして扱う） */
export const emptyStatusLabel = (code) => MAP[String(code)] ?? null;

/** 埋まり具合の重み。満車=1 / 混雑=0.5 / 空=0。集計側もこれを使う */
export const BUSY_WEIGHT = { "満車": 1, "混雑": 0.5, "空": 0 };
